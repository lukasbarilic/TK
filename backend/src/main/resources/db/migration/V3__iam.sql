-- Používatelia, roly a oprávnenia (HLD kap. 8.2 a 8.4).

CREATE TABLE user_account (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(100) NOT NULL UNIQUE,
    display_name        VARCHAR(200) NOT NULL,
    email               VARCHAR(200) NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    auth_provider       VARCHAR(20)  NOT NULL DEFAULT 'LOCAL'
        CHECK (auth_provider IN ('LOCAL', 'OIDC')),
    external_subject    VARCHAR(200) NULL,
    password_hash       VARCHAR(255) NULL,
    last_login_at       TIMESTAMPTZ  NULL,
    language            VARCHAR(10)  NULL,
    must_change_password BOOLEAN     NOT NULL DEFAULT FALSE,
    failed_login_count  INT          NOT NULL DEFAULT 0,
    locked_until        TIMESTAMPTZ  NULL,
    password_changed_at TIMESTAMPTZ  NULL,
    default_reception_id BIGINT      NULL REFERENCES reception (id),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          BIGINT       NULL REFERENCES user_account (id),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by          BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50)  NOT NULL UNIQUE,
    name        VARCHAR(200) NOT NULL,
    description VARCHAR(500) NULL,
    system_role BOOLEAN      NOT NULL DEFAULT FALSE,
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT       NULL REFERENCES user_account (id),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by  BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE permission (
    code        VARCHAR(50)  PRIMARY KEY,
    module      VARCHAR(50)  NOT NULL,
    description VARCHAR(500) NOT NULL,
    has_limit   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE role_permission (
    role_id         BIGINT      NOT NULL REFERENCES role (id),
    permission_code VARCHAR(50) NOT NULL REFERENCES permission (code),
    limit_value     INT         NULL CHECK (limit_value BETWEEN 1 AND 365),
    PRIMARY KEY (role_id, permission_code)
);

CREATE TABLE user_role (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES user_account (id),
    role_id      BIGINT NOT NULL REFERENCES role (id),
    centre_id    BIGINT NULL REFERENCES centre (id),
    reception_id BIGINT NULL REFERENCES reception (id),
    valid_from   DATE   NULL,
    valid_to     DATE   NULL,
    CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_from <= valid_to)
);
CREATE INDEX user_role_user_idx ON user_role (user_id);

-- created_by / updated_by vo všetkých existujúcich tabuľkách odkazujú na user_account.
DO $$
DECLARE
    t RECORD;
BEGIN
    FOR t IN
        SELECT c1.table_name
        FROM information_schema.columns c1
        JOIN information_schema.columns c2
          ON c2.table_schema = c1.table_schema AND c2.table_name = c1.table_name
         AND c2.column_name = 'updated_by'
        JOIN information_schema.tables tb
          ON tb.table_schema = c1.table_schema AND tb.table_name = c1.table_name
         AND tb.table_type = 'BASE TABLE'
        WHERE c1.table_schema = current_schema()
          AND c1.column_name = 'created_by'
          AND c1.table_name NOT IN ('user_account', 'role')
    LOOP
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (created_by) REFERENCES user_account (id)',
                       t.table_name, t.table_name || '_created_by_fk');
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (updated_by) REFERENCES user_account (id)',
                       t.table_name, t.table_name || '_updated_by_fk');
    END LOOP;
END $$;
