-- Poznámka a komentáre k rezervačnej karte (TK-45).

ALTER TABLE reservation
    ADD COLUMN note         VARCHAR(2000) NULL,
    ADD COLUMN note_in_plan BOOLEAN       NOT NULL DEFAULT FALSE;

-- Komentár sa nedá upraviť, len skryť (hidden_at, hidden_by).
CREATE TABLE reservation_comment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT        NOT NULL REFERENCES reservation (id),
    author_id      BIGINT        NOT NULL REFERENCES user_account (id),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    text           VARCHAR(2000) NOT NULL CHECK (length(btrim(text)) > 0),
    hidden_at      TIMESTAMPTZ   NULL,
    hidden_by      BIGINT        NULL REFERENCES user_account (id),
    CHECK ((hidden_at IS NULL) = (hidden_by IS NULL))
);

CREATE INDEX reservation_comment_reservation_idx ON reservation_comment (reservation_id, id);

-- Nový alebo skrytý komentár mení počet komentárov na pásiku plánu: zvýši počítadlo zmien recepcií karty.
CREATE FUNCTION trg_reservation_comment_bump_seq() RETURNS TRIGGER
    LANGUAGE plpgsql AS $$
BEGIN
    PERFORM bump_reception_seq_of_reservation(NEW.reservation_id);
    RETURN NULL;
END $$;

CREATE TRIGGER reservation_comment_bump_seq AFTER INSERT OR UPDATE ON reservation_comment
    FOR EACH ROW EXECUTE FUNCTION trg_reservation_comment_bump_seq();
