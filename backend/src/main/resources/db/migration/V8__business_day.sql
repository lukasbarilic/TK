-- Obchodný deň recepcie a pravidlá nočnej uzávierky (HLD kap. 4.5 a 5.8).
-- (Číslo V8, lebo V7 je už obsadená migráciou audit čítania.)

CREATE TABLE business_day (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reception_id    BIGINT      NOT NULL REFERENCES reception (id),
    business_date   DATE        NOT NULL,
    status          VARCHAR(10) NOT NULL CHECK (status IN ('OPEN', 'CLOSED')),
    opened_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at       TIMESTAMPTZ NULL,
    closed_by       BIGINT      NULL REFERENCES user_account (id),
    closing_summary JSONB       NULL,
    UNIQUE (reception_id, business_date)
);
-- Práve jeden otvorený deň na recepciu.
CREATE UNIQUE INDEX business_day_one_open_idx ON business_day (reception_id) WHERE status = 'OPEN';

CREATE TABLE closing_rule (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(50) NOT NULL,
    enabled      BOOLEAN     NOT NULL DEFAULT TRUE,
    severity     VARCHAR(10) NOT NULL CHECK (severity IN ('BLOCKING', 'INFO')),
    reception_id BIGINT      NULL REFERENCES reception (id)
);
-- Jedno pravidlo na kód a recepciu; reception_id NULL = všetky recepcie.
CREATE UNIQUE INDEX closing_rule_code_reception_idx ON closing_rule (code, COALESCE(reception_id, 0));

