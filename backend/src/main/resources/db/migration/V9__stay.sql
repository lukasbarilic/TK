-- Pobyty (HLD kap. 4.2, 5.2) a pravidlo nočnej uzávierky CHECKED_IN_WITHOUT_STAY.
-- (Číslo V9, lebo V8 je už obsadená migráciou obchodného dňa.)

CREATE TABLE stay (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id        BIGINT      NOT NULL REFERENCES reservation (id),
    bed_id                BIGINT      NOT NULL REFERENCES bed (id),
    date_from             DATE        NOT NULL,
    date_to               DATE        NOT NULL,
    price_category_id     BIGINT      NOT NULL REFERENCES room_category (id),
    surcharge_category_id BIGINT      NULL REFERENCES room_category (id),
    locked                BOOLEAN     NOT NULL DEFAULT FALSE,
    version               BIGINT      NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by            BIGINT      NULL,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by            BIGINT      NULL,
    CONSTRAINT stay_dates_check CHECK (date_from < date_to),
    -- Posledná poistka: dva pobyty na jednom lôžku sa nesmú prekrývať (polootvorený interval).
    CONSTRAINT stay_bed_no_overlap EXCLUDE USING gist (
        bed_id WITH =,
        daterange(date_from, date_to, '[)') WITH &&
    )
);
CREATE INDEX stay_reservation_idx ON stay (reservation_id);

INSERT INTO closing_rule (code, enabled, severity) VALUES ('CHECKED_IN_WITHOUT_STAY', TRUE, 'BLOCKING');
