-- Audit zápisov (HLD kap. 7.1–7.3): len na pridávanie, mesačné partície podľa occurred_at.
-- Partície pre aktuálny a nasledujúce mesiace vytvára aplikácia pri štarte (AuditPartitionInitializer).
-- audit_change nesie occurred_at udalosti, lebo cudzí kľúč na partitioned tabuľku musí obsahovať kľúč partície.

CREATE TABLE audit_event (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_uid          UUID         NOT NULL DEFAULT gen_random_uuid(),
    event_type         VARCHAR(10)  NOT NULL CHECK (event_type IN ('WRITE', 'READ', 'LOGIN')),
    occurred_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    user_id            BIGINT       NULL REFERENCES user_account (id),
    username           VARCHAR(100) NOT NULL,
    roles              VARCHAR(500) NULL,
    operation          VARCHAR(100) NOT NULL,
    use_case           VARCHAR(50)  NULL,
    target_type        VARCHAR(100) NULL,
    target_id          BIGINT       NULL,
    outcome            VARCHAR(10)  NOT NULL CHECK (outcome IN ('SUCCESS', 'REJECTED')),
    error_code         VARCHAR(100) NULL,
    request_payload    JSONB        NULL,
    confirmed_warnings JSONB        NULL,
    request_id         VARCHAR(100) NULL,
    client_ip          VARCHAR(100) NULL,
    user_agent         VARCHAR(500) NULL,
    PRIMARY KEY (id, occurred_at)
) PARTITION BY RANGE (occurred_at);

CREATE TABLE audit_change (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    audit_event_id BIGINT       NOT NULL,
    occurred_at    TIMESTAMPTZ  NOT NULL,
    entity_type    VARCHAR(100) NOT NULL,
    entity_id      BIGINT       NULL,
    change_type    VARCHAR(10)  NOT NULL CHECK (change_type IN ('CREATE', 'UPDATE', 'DELETE')),
    before_state   JSONB        NULL,
    after_state    JSONB        NULL,
    changed_fields JSONB        NULL,
    PRIMARY KEY (id, occurred_at),
    FOREIGN KEY (audit_event_id, occurred_at) REFERENCES audit_event (id, occurred_at)
) PARTITION BY RANGE (occurred_at);

CREATE INDEX audit_event_occurred_idx ON audit_event (occurred_at);
CREATE INDEX audit_event_user_idx ON audit_event (user_id, occurred_at);
CREATE INDEX audit_event_operation_idx ON audit_event (operation, occurred_at);
CREATE INDEX audit_event_id_idx ON audit_event (id);
CREATE INDEX audit_change_event_idx ON audit_change (audit_event_id);
CREATE INDEX audit_change_entity_idx ON audit_change (entity_type, entity_id);

-- Audit je len na pridávanie: UPDATE a DELETE sa odmietne (trigger sa dedí na všetky partície).
CREATE FUNCTION audit_reject_modification() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Audit tabuľka % je len na pridávanie (% nie je povolený).', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_event_append_only
    BEFORE UPDATE OR DELETE ON audit_event
    FOR EACH ROW EXECUTE FUNCTION audit_reject_modification();

CREATE TRIGGER audit_change_append_only
    BEFORE UPDATE OR DELETE ON audit_change
    FOR EACH ROW EXECUTE FUNCTION audit_reject_modification();
