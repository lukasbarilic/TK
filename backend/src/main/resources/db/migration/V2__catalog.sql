CREATE TABLE room (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id           BIGINT      NOT NULL REFERENCES building (id),
    number                VARCHAR(30) NOT NULL,
    floor                 VARCHAR(30) NULL,
    category_id           BIGINT      NOT NULL REFERENCES room_category (id),
    secondary_category_id BIGINT      NULL REFERENCES room_category (id),
    department_id         BIGINT      NULL REFERENCES department (id),
    regular_beds          INT         NOT NULL CHECK (regular_beds >= 0),
    extra_beds            INT         NOT NULL DEFAULT 0 CHECK (extra_beds >= 0),
    extra_bed_max_age     INT         NULL,
    bookable              BOOLEAN     NOT NULL DEFAULT TRUE,
    active                BOOLEAN     NOT NULL DEFAULT TRUE,
    version               BIGINT      NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by            BIGINT      NULL,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by            BIGINT      NULL,
    UNIQUE (building_id, number)
);
CREATE INDEX room_category_idx ON room (category_id);

CREATE TABLE bed (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT      NOT NULL REFERENCES room (id),
    bed_number INT         NOT NULL CHECK (bed_number > 0),
    type       VARCHAR(10) NOT NULL CHECK (type IN ('REGULAR', 'EXTRA')),
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    version    BIGINT      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT      NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by BIGINT      NULL,
    UNIQUE (room_id, bed_number)
);

-- Počet lôžok EXTRA musí zodpovedať room.extra_beds (kontrola po dokončení transakcie).
CREATE FUNCTION check_room_extra_beds() RETURNS trigger AS $$
DECLARE
    v_room_id BIGINT;
    v_expected INT;
    v_actual INT;
BEGIN
    IF TG_TABLE_NAME = 'room' THEN
        v_room_id := NEW.id;
    ELSIF TG_OP = 'DELETE' THEN
        v_room_id := OLD.room_id;
    ELSE
        v_room_id := NEW.room_id;
    END IF;
    SELECT extra_beds INTO v_expected FROM room WHERE id = v_room_id;
    IF v_expected IS NULL THEN
        RETURN NULL; -- izba už neexistuje
    END IF;
    SELECT count(*) INTO v_actual FROM bed WHERE room_id = v_room_id AND type = 'EXTRA';
    IF v_actual <> v_expected THEN
        RAISE EXCEPTION 'Izba %: počet lôžok EXTRA (%) sa nerovná room.extra_beds (%)',
            v_room_id, v_actual, v_expected USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER bed_extra_count_check
    AFTER INSERT OR UPDATE OR DELETE ON bed
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_room_extra_beds();
CREATE CONSTRAINT TRIGGER room_extra_count_check
    AFTER INSERT OR UPDATE OF extra_beds ON room
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_room_extra_beds();

