-- Klienti a rezervačné karty (HLD kap. 4.2). Pobyty (stay) pribudnú v P09.
-- Rodné čísla, adresy a doklady sa v module ubytovania nepoužívajú, preto tu nie sú.

CREATE EXTENSION IF NOT EXISTS unaccent;

-- unaccent() nie je označená IMMUTABLE, preto obal pre indexy (výraz v indexe musí byť immutable).
CREATE FUNCTION f_unaccent(text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
    AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

CREATE TABLE client (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(100) NOT NULL,
    last_name   VARCHAR(100) NOT NULL,
    birth_date  DATE         NULL,
    nationality VARCHAR(2)   NULL,
    email       VARCHAR(200) NULL,
    phone       VARCHAR(50)  NULL,
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT       NULL REFERENCES user_account (id),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by  BIGINT       NULL REFERENCES user_account (id)
);
CREATE INDEX client_name_trgm_idx ON client
    USING gin (f_unaccent(lower(last_name || ' ' || first_name)) gin_trgm_ops);

CREATE TABLE reservation_group (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(200) NOT NULL,
    contact_person VARCHAR(200) NULL,
    date_from      DATE         NULL,
    date_to        DATE         NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     BIGINT       NULL REFERENCES user_account (id),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by     BIGINT       NULL REFERENCES user_account (id)
);

-- Malá skupina (partneri v jednej izbe).
CREATE TABLE reservation_party (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

-- Čísla nových kariet; demo karty majú čísla R100001+, preto sa začína vyššie.
CREATE SEQUENCE reservation_number_seq START WITH 200001;

CREATE TABLE reservation (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_number VARCHAR(20)  NOT NULL UNIQUE,
    status             VARCHAR(20)  NOT NULL DEFAULT 'RESERVED'
        CHECK (status IN ('RESERVED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED')),
    arrival_date       DATE         NOT NULL,
    departure_date     DATE         NOT NULL,
    booked_category_id BIGINT       NOT NULL REFERENCES room_category (id),
    payer_id           BIGINT       NOT NULL REFERENCES payer (id),
    group_id           BIGINT       NULL REFERENCES reservation_group (id),
    party_id           BIGINT       NULL REFERENCES reservation_party (id),
    exclusive_room_use BOOLEAN      NOT NULL DEFAULT FALSE,
    price_category_mode VARCHAR(20) NOT NULL DEFAULT 'FOLLOW_ROOM'
        CHECK (price_category_mode IN ('FOLLOW_ROOM', 'KEEP_BOOKED', 'MANUAL')),
    price_type         VARCHAR(20)  NOT NULL DEFAULT 'PER_BED'
        CHECK (price_type IN ('PER_BED', 'PER_ROOM')),
    do_not_move        BOOLEAN      NOT NULL DEFAULT FALSE,
    early_check_in     BOOLEAN      NOT NULL DEFAULT FALSE,
    late_check_out     BOOLEAN      NOT NULL DEFAULT FALSE,
    adults             INT          NOT NULL DEFAULT 1 CHECK (adults >= 1),
    children           INT          NOT NULL DEFAULT 0 CHECK (children >= 0),
    version            BIGINT       NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         BIGINT       NULL REFERENCES user_account (id),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by         BIGINT       NULL REFERENCES user_account (id),
    CONSTRAINT reservation_dates_chk CHECK (arrival_date < departure_date),
    CONSTRAINT reservation_nights_chk CHECK (departure_date - arrival_date <= 365)
);
CREATE INDEX reservation_dates_idx ON reservation (arrival_date, departure_date);
CREATE INDEX reservation_status_idx ON reservation (status);
CREATE INDEX reservation_party_idx ON reservation (party_id);
CREATE INDEX reservation_number_trgm_idx ON reservation
    USING gin (f_unaccent(lower(reservation_number)) gin_trgm_ops);

CREATE TABLE reservation_guest (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT       NOT NULL REFERENCES reservation (id),
    client_id      BIGINT       NOT NULL REFERENCES client (id),
    primary_guest  BOOLEAN      NOT NULL DEFAULT FALSE,
    cancelled      BOOLEAN      NOT NULL DEFAULT FALSE,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     BIGINT       NULL REFERENCES user_account (id),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by     BIGINT       NULL REFERENCES user_account (id),
    UNIQUE (reservation_id, client_id)
);
CREATE INDEX reservation_guest_client_idx ON reservation_guest (client_id);
