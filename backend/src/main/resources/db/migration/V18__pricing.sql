CREATE TABLE package (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,
    name       VARCHAR(200) NOT NULL,
    board_type VARCHAR(10)  NOT NULL DEFAULT 'NONE' CHECK (board_type IN ('NONE', 'BB', 'HB', 'FB')),
    procedures_per_day INT  NOT NULL DEFAULT 0 CHECK (procedures_per_day >= 0),
    min_nights INT          NULL CHECK (min_nights > 0),
    max_nights INT          NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT package_nights_chk CHECK (max_nights IS NULL OR min_nights IS NULL OR max_nights >= min_nights),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE package_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT       NOT NULL REFERENCES package (id),
    service_code VARCHAR(30) NOT NULL,
    name       VARCHAR(200) NOT NULL,
    part       VARCHAR(20)  NOT NULL CHECK (part IN ('ACCOMMODATION', 'FOOD', 'SERVICES')),
    allocated_amount NUMERIC(12,2) NOT NULL CHECK (allocated_amount >= 0),
    vat_rate   NUMERIC(5,2) NOT NULL CHECK (vat_rate >= 0),
    unit       VARCHAR(20)  NOT NULL CHECK (unit IN ('PER_PERSON', 'PER_ROOM')),
    frequency  VARCHAR(20)  NOT NULL CHECK (frequency IN ('PER_NIGHT', 'PER_STAY', 'PER_WEEK')),
    quantity   INT          NOT NULL DEFAULT 1 CHECK (quantity > 0),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);
CREATE INDEX package_item_package_idx ON package_item (package_id);

CREATE TABLE price_list (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200) NOT NULL,
    valid_from DATE         NOT NULL,
    valid_to   DATE         NULL,
    status     VARCHAR(20)  NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    CONSTRAINT price_list_valid_chk CHECK (valid_to IS NULL OR valid_to > valid_from),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE price_season (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_id BIGINT    NOT NULL REFERENCES price_list (id),
    code       VARCHAR(30)  NOT NULL,
    name       VARCHAR(200) NOT NULL,
    date_from  DATE         NOT NULL,
    date_to    DATE         NOT NULL,
    priority   INT          NOT NULL DEFAULT 0,
    CONSTRAINT price_season_dates_chk CHECK (date_to > date_from),
    UNIQUE (price_list_id, code),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE price_rate (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_season_id BIGINT  NOT NULL REFERENCES price_season (id),
    room_category_id BIGINT NOT NULL REFERENCES room_category (id),
    package_id BIGINT       NULL REFERENCES package (id),
    price_type VARCHAR(20)  NOT NULL CHECK (price_type IN ('PER_BED', 'PER_ROOM')),
    occupancy  INT          NULL CHECK (occupancy > 0),
    amount     NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    extra_bed_amount NUMERIC(12,2) NULL CHECK (extra_bed_amount >= 0),
    unit       VARCHAR(20)  NOT NULL DEFAULT 'PER_NIGHT' CHECK (unit IN ('PER_NIGHT', 'PER_STAY')),
    nights     INT          NULL CHECK (nights > 0),
    extra_night_amount NUMERIC(12,2) NULL CHECK (extra_night_amount >= 0),
    short_stay_rule VARCHAR(20) NULL CHECK (short_stay_rule IN ('PRORATE', 'FULL')),
    min_nights INT          NULL CHECK (min_nights > 0),
    max_nights INT          NULL,
    CONSTRAINT price_rate_per_stay_chk CHECK (unit = 'PER_NIGHT' OR nights IS NOT NULL),
    CONSTRAINT price_rate_nights_chk CHECK (max_nights IS NULL OR min_nights IS NULL OR max_nights >= min_nights),
    -- NULL v package_id a occupancy sa porovnáva ako rovnaká hodnota (PostgreSQL 15+).
    CONSTRAINT price_rate_key UNIQUE NULLS NOT DISTINCT
        (price_season_id, room_category_id, package_id, price_type, occupancy, unit),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE occupancy_modifier (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_id BIGINT    NOT NULL REFERENCES price_list (id),
    room_category_id BIGINT NULL REFERENCES room_category (id),
    person_order INT        NULL CHECK (person_order > 0),
    age_from   INT          NULL CHECK (age_from >= 0),
    age_to     INT          NULL,
    bed_type   VARCHAR(10)  NULL CHECK (bed_type IN ('REGULAR', 'EXTRA')),
    kind       VARCHAR(20)  NOT NULL CHECK (kind IN ('FIXED_PRICE', 'PERCENT', 'AMOUNT')),
    value      NUMERIC(12,2) NOT NULL,
    priority   INT          NOT NULL DEFAULT 0,
    CONSTRAINT occupancy_modifier_age_chk CHECK (age_to IS NULL OR age_from IS NULL OR age_to >= age_from),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE price_surcharge (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_id BIGINT    NOT NULL REFERENCES price_list (id),
    code       VARCHAR(30)  NOT NULL,
    type       VARCHAR(20)  NOT NULL
        CHECK (type IN ('EXTRA_BED', 'SINGLE_USE', 'HELD_BED', 'EARLY_CHECK_IN', 'LATE_CHECK_OUT')),
    amount     NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    amount_kind VARCHAR(20) NOT NULL CHECK (amount_kind IN ('PER_NIGHT', 'PER_STAY', 'PERCENT')),
    vat_rate   NUMERIC(5,2) NOT NULL CHECK (vat_rate >= 0),
    UNIQUE (price_list_id, code),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE price_discount (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_id BIGINT    NOT NULL REFERENCES price_list (id),
    code       VARCHAR(30)  NOT NULL,
    type       VARCHAR(20)  NOT NULL CHECK (type IN ('LENGTH', 'EARLY_BOOKING', 'SENIOR', 'PROMO')),
    percent    NUMERIC(5,2) NULL CHECK (percent BETWEEN 0 AND 100),
    amount     NUMERIC(12,2) NULL CHECK (amount >= 0),
    min_nights INT          NULL CHECK (min_nights > 0),
    min_days_before INT     NULL CHECK (min_days_before >= 0),
    age_from   INT          NULL CHECK (age_from >= 0),
    promo_code VARCHAR(50)  NULL,
    stackable  BOOLEAN      NOT NULL DEFAULT FALSE,
    priority   INT          NOT NULL DEFAULT 0,
    valid_from DATE         NULL,
    valid_to   DATE         NULL,
    CONSTRAINT price_discount_value_chk CHECK ((percent IS NULL) <> (amount IS NULL)),
    CONSTRAINT price_discount_valid_chk CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to >= valid_from),
    UNIQUE (price_list_id, code),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

CREATE TABLE price_discount_target (
