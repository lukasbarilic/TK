    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

