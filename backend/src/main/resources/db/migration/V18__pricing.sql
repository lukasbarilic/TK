-- Modul pricing: schéma cenníkov, balíkov a kalkulácie ceny (TK-55, docs/HLD-cenotvorba.md kap. 4 a 8).
-- Cena je brutto za lôžko a noc (EUR). Cenník je jeden pre všetky strediská a platiteľov,
-- preto price_list nemá centre_id ani payer_id. Výpočet ceny pribudne v ďalších tiketoch (C2+).

CREATE TABLE age_group (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,
    name       VARCHAR(200) NOT NULL,
    age_from   INT          NOT NULL CHECK (age_from >= 0),
    age_to     INT          NULL,
    CONSTRAINT age_group_range_chk CHECK (age_to IS NULL OR age_to >= age_from),
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT       NULL REFERENCES user_account (id),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by BIGINT       NULL REFERENCES user_account (id)
);

