-- Audit čítania osobných údajov (HLD kap. 7.2 a 7.4): ktorých klientov sa čítanie týkalo a v akom rozsahu.
-- Len na pridávanie, mesačné partície podľa occurred_at (partície vytvára AuditPartitionInitializer).

CREATE TABLE audit_subject_access (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    audit_event_id BIGINT      NOT NULL,
    occurred_at    TIMESTAMPTZ NOT NULL,
    client_id      BIGINT      NOT NULL,
    data_scope     VARCHAR(10) NOT NULL CHECK (data_scope IN ('NAME', 'CONTACT', 'FULL')),
    PRIMARY KEY (id, occurred_at),
    FOREIGN KEY (audit_event_id, occurred_at) REFERENCES audit_event (id, occurred_at)
) PARTITION BY RANGE (occurred_at);

CREATE INDEX audit_subject_access_event_idx ON audit_subject_access (audit_event_id);
CREATE INDEX audit_subject_access_client_idx ON audit_subject_access (client_id, occurred_at);

CREATE TRIGGER audit_subject_access_append_only
    BEFORE UPDATE OR DELETE ON audit_subject_access
    FOR EACH ROW EXECUTE FUNCTION audit_reject_modification();
